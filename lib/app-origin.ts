/**
 * Resolution of the public origin used for the Stripe redirect URLs.
 *
 * This module is intentionally free of Stripe, Firebase and billing imports:
 * several endpoints need the origin and must stay loadable in environments
 * where the billing configuration is not present (tests, for instance).
 */

/**
 * Hosts that are allowed to receive the post-checkout redirect.
 *
 * The redirect has to land on the very same origin the member started from:
 * the platform session cookie and the Firebase session live on that origin, so
 * a different host means the member is bounced back to the login screen.
 */
const ALLOWED_APP_HOSTS = new Set([
    'app.theactorscopilot.com',
    'theactorscopilot.com',
    'www.theactorscopilot.com',
    'v0-self-tape-copilot.vercel.app',
]);

/** Preview and production hosts generated by Vercel for this project. */
const VERCEL_APP_HOST_PATTERN = /^actors-copilot(-[a-z0-9]+)*\.vercel\.app$/;

/**
 * Tells whether a host may be used as the post-checkout destination.
 *
 * @param host - The hostname to validate, without the port.
 * @returns {boolean} True when the host belongs to this project.
 */
export function isAllowedAppHost(host: string): boolean {
    const normalized = host.trim().toLowerCase();
    if (!normalized) return false;
    if (ALLOWED_APP_HOSTS.has(normalized)) return true;
    return VERCEL_APP_HOST_PATTERN.test(normalized);
}

/**
 * Resolves the public origin of the incoming request.
 *
 * The checkout redirect is built from this value so that the member returns to
 * the exact host they started from. Anything that is not a host of this project
 * falls back to the configured public app URL, which keeps the endpoint from
 * being usable as an open redirect.
 *
 * @param headers - The incoming request headers.
 * @returns {string} The origin to use for the Stripe success and cancel URLs.
 */
export function resolveAppUrl(headers: Headers): string {
    const fallback = process.env.NEXT_PUBLIC_APP_URL || 'http://localhost:3000';

    const rawHost = (headers.get('x-forwarded-host') || headers.get('host') || '')
        .split(',')[0]
        .trim();
    if (!rawHost) return fallback;

    const hostOnly = rawHost.replace(/:\d+$/, '');
    if (!isAllowedAppHost(hostOnly)) return fallback;

    const forwardedProto = headers.get('x-forwarded-proto')?.split(',')[0]?.trim();
    const proto = forwardedProto || 'https';

    return `${proto}://${rawHost}`;
}

/**
 * Compares two URLs by host, ignoring the scheme, the path and the query.
 *
 * @param url - The first URL.
 * @param appUrl - The second URL.
 * @returns {boolean} True when both URLs point at the same host.
 */
export function isSameAppOrigin(url: string, appUrl: string): boolean {
    try {
        return new URL(url).host.toLowerCase() === new URL(appUrl).host.toLowerCase();
    } catch {
        return false;
    }
}
